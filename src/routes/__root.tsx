function ErrorComponent({ error, reset }: ErrorComponentProps) {
  console.error(error);
  const router = useRouter();
  useEffect(() => {
    reportLovableError(error, { boundary: "tanstack_root_error_component" });
  }, [error]);

  return (
    <div className="flex min-h-screen items-center justify-center bg-background bg-halftone px-4">
      <div className="max-w-md text-center" role="alert">
        <h1 className="font-display text-3xl text-secondary">Whoops, too much chaos.</h1>
        <p className="mt-3 text-sm text-muted-foreground">
          Something went wrong loading this page. Try again in a moment.
        </p>
        <div className="mt-8 flex flex-wrap justify-center gap-3">
          <button
            onClick={() => {
              router.invalidate();
              reset();
            }}
            className="inline-flex h-11 items-center justify-center rounded-xl border-2 border-ink bg-primary px-6 font-display text-sm uppercase text-primary-foreground shadow-hard-pink"
          >
            Try again
          </button>
          <a
            href="/"
            className="inline-flex h-11 items-center justify-center rounded-xl border-2 border-border px-6 font-display text-sm uppercase text-foreground"
          >
            Go home
          </a>
        </div>
      </div>
    </div>
  );
}

